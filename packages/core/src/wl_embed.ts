/**
 * The whitelist settings written into the filter file itself, so the Whitelist tab can open the file again and edit it.
 * Port of poe_price_trade/wl_embed.py. The game ignores comment lines; every line starts with "#" and is plain ASCII
 * (compressed JSON as base64, cut into short lines):
 *
 *     # poe-checker-config: <chunk>        (one or more lines, joined in file order)
 *
 * The compression must give the bytes Python's `zlib.compress(raw, 9)` gives: pako 2.1.0 does (node:zlib does not).
 */
import pako from "pako";
import { PY_S, b64decode, b64encode, dumps, has, isDict, splitLines } from "./py.ts";

export const MARK = "# poe-checker-config:";
export const SCHEMA = 1;
const CHUNK = 110;
export const WL_HEADER = "# === PoE Checker - Whitelist";
export const TIER_HEADER_START = "# Generated by PoE Price & Trade Checker";

const GAME_KEYS = ["wl_item_tier", "wl_cat_tier", "wl_class_tier", "wl_unique_tier", "wl_block_tier", "wl_rarity_rows", "wl_equip_rows",
  "wl_lists", "wl_item_stack", "whitelist_gem_uncut", "whitelist_gem_names", "whitelist_custom"];
const SHARED_KEYS = ["wl_v2", "wl_tier_format", "wl_tier_stack", "wl_tier_style", "whitelist_gold", "whitelist_gold_min", "wl_map_on",
  "wl_map_tier_min", "wl_map_rarity_min", "whitelist_gem_tier"];

export const configKeys = (game: string): string[] => [...SHARED_KEYS, ...GAME_KEYS.map((k) => `${k}_${game}`)];

/** Just the whitelist keys of a filter_gen config dict. */
export function whitelistPart(cfg: Record<string, any>, game: string): Record<string, any> {
  const out: Record<string, any> = {};
  for (const k of configKeys(game)) if (has(cfg, k)) out[k] = cfg[k];
  return out;
}

export function embedLines(cfg: Record<string, any>, game: string, version = ""): string[] {
  const payload = { schema: SCHEMA, game, app: version, cfg: whitelistPart(cfg, game) };
  const raw = new TextEncoder().encode(dumps(payload, { ensureAscii: true, sortKeys: true, separators: [",", ":"] }));
  const b64 = b64encode(pako.deflate(raw, { level: 9 }));
  const out: string[] = [];
  for (let i = 0; i < b64.length; i += CHUNK) out.push(`${MARK} ${b64.slice(i, i + CHUNK)}`);
  return out;
}

/** `text` (a whitelist filter) + the settings as comment lines at its end. */
export function embed(text: string, cfg: Record<string, any>, game: string, version = ""): string {
  let end = text.length;
  while (end > 0 && text[end - 1] === "\n") end--;
  const body = text.slice(0, end);
  return body + "\n\n# settings of this filter (the Whitelist tab reads them back; the game ignores them)\n" +
    embedLines(cfg, game, version).join("\n") + "\n";
}

export interface Embedded {
  schema?: number;
  game: string;
  app?: string;
  cfg: Record<string, any>;
}

const CHUNK_RE = new RegExp(`^${MARK}[${PY_S}]*([^${PY_S}]+)[${PY_S}]*$`); // MARK has no regex metacharacters

/** The embedded {"schema", "game", "app", "cfg"} of a filter file, or null (no config / unreadable). */
export function extract(text: string): Embedded | null {
  const chunks: string[] = [];
  for (const l of splitLines(text)) {
    const m = CHUNK_RE.exec(l);
    if (m) chunks.push(m[1]);
  }
  if (!chunks.length) return null;
  let data: any;
  try {
    const inflated = pako.inflate(b64decode(chunks.join("")));
    for (const b of inflated) if (b > 127) return null; // .decode("ascii") fails
    data = JSON.parse(new TextDecoder().decode(inflated));
  } catch {
    return null;
  }
  if (!isDict(data) || !isDict(data.cfg) || (data.game !== "poe1" && data.game !== "poe2")) return null;
  return data as Embedded;
}

/** "ok" (has settings) | "no_config" (a whitelist file from before settings were embedded) | "tier" (the NeverSink tab's file) | "foreign". */
export function classify(text: string): "ok" | "no_config" | "tier" | "foreign" {
  if (extract(text) !== null) return "ok";
  const head = text.slice(0, 600);
  if (head.includes(WL_HEADER)) return "no_config";
  if (head.includes(TIER_HEADER_START)) return "tier";
  return "foreign";
}
